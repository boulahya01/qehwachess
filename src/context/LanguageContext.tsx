interface LanguageContextValue {
  language: Language;
  hasChosenLanguage: boolean;
  chooseLanguage: (language: Language) => void;
  t: (text: string) => string;
  languageNames: Record<Language, string>;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem('qehwa-language');
    return saved === 'en' || saved === 'fr' || saved === 'ar' ? saved : 'en';
  });
  const [hasChosenLanguage, setHasChosenLanguage] = useState(
    () => localStorage.getItem('qehwa-language') !== null
  );

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  }, [language]);

  function chooseLanguage(nextLanguage: Language) {
    localStorage.setItem('qehwa-language', nextLanguage);
    setLanguage(nextLanguage);
    setHasChosenLanguage(true);
  }

  function t(text: string) {
    return language === 'en' ? text : authTranslations[language][text] ?? v2Translations[language][text] ?? translations[language][text] ?? text;
  }

  return (
    <LanguageContext.Provider value={{ language, hasChosenLanguage, chooseLanguage, t, languageNames }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}
